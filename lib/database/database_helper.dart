  // --- Database Initialization ---
  Future<Database> get database async {
    if (_database != null) return _database!;
    _database = await initDatabase();
    return _database!;
  }

  Future<Database> initDatabase() async {
    String path = join(await getDatabasesPath(), 'bethakji_yadi.db');

    return await openDatabase(
      path,
      version: 4, // Incremented version for audio asset column
      onCreate: (db, version) async {
        await _createBethakjiTable(db);
        await _createPathavaliTable(db);
      },
      onUpgrade: (db, oldVersion, newVersion) async {
        // A non-destructive upgrade.
        if (oldVersion < 3) {
          // If the old version didn't have the pathavali table, add it.
          await _createPathavaliTable(db);
        }
        if (oldVersion < 4) {
          // If the old version doesn't have the audioAsset column, add it and populate it.
          await db.execute('ALTER TABLE pathavali ADD COLUMN audioAsset TEXT');
          final batch = db.batch();
          for (final item in pathavaliList) {
            if (item.audioAsset != null) {
              batch.update(
                'pathavali',
                {'audioAsset': item.audioAsset},
                where: 'id = ?',
                whereArgs: [item.id],
              );
            }
          }
          await batch.commit(noResult: true);
        }
      },
    );
  }

  Future<void> _createBethakjiTable(Database db) async {
    await db.execute('''
      CREATE TABLE IF NOT EXISTS $tableName (
        id INTEGER PRIMARY KEY,
        number TEXT,
        name TEXT NOT NULL,
        address TEXT,
        contacts TEXT,
        mahatmy TEXT,
        directions TEXT,
        rules TEXT,
        isFavorite INTEGER DEFAULT 0
      )
    ''');
    final batch = db.batch();
    for (final item in bethakji84List) {
      batch.insert(
        tableName,
        item.toMap(),
        conflictAlgorithm: ConflictAlgorithm.replace,
      );
    }
    await batch.commit(noResult: true);
  }

  Future<void> _createPathavaliTable(Database db) async {
    await db.execute('''
      CREATE TABLE IF NOT EXISTS pathavali(
        id TEXT PRIMARY KEY,
        title TEXT NOT NULL,
        content TEXT NOT NULL,
        isFavorite INTEGER NOT NULL DEFAULT 0,
