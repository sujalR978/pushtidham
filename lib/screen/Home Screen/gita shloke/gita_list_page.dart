  void _filterShlokas(String query) {
    setState(() {
      if (query.trim().isEmpty) {
        _filteredShlokas = _allShlokas;
      } else {
        _filteredShlokas = _allShlokas.where((item) {
          return item.title.toLowerCase().contains(query.toLowerCase()) ||
              item.chapterVerse.contains(query) ||
              item.GujaratiArth.contains(query);
        }).toList();
      }
    });
  }

